// 1. 개별 케이스 검증
// ──────────────────────────────────────────────────────────────────
describe("detectSmishing() — 위험 문자 (50건)", () => {
  test.each(DANGEROUS.map((msg, i) => [i + 1, msg] as [number, string]))(
    "#%i 위험 문자 → high 또는 medium",
    (_, msg) => {
      const r = detectSmishing(msg);
      expect(["high", "medium"]).toContain(r.risk);
    }
  );
});

describe("detectSmishing() — 정상 문자 (50건)", () => {
  test.each(NORMAL.map((msg, i) => [i + 1, msg] as [number, string]))(
    "#%i 정상 문자 → low",
    (_, msg) => {
      const r = detectSmishing(msg);
      expect(r.risk).toBe("low");
    }
  );
});

// ──────────────────────────────────────────────────────────────────
// 2. 재현율 / 오탐률 집계 (수용 기준 검증)
// ──────────────────────────────────────────────────────────────────
describe("수용 기준 — 재현율 ≥ 0.85, 오탐률 ≤ 0.10", () => {
  test("위험 50건 중 high|medium 비율이 0.85 이상", () => {
    const detected = DANGEROUS.filter((m) => {
      const r = detectSmishing(m);
      return r.risk === "high" || r.risk === "medium";
    }).length;
    const recall = detected / DANGEROUS.length;
    expect(recall).toBeGreaterThanOrEqual(0.85);
  });

  test("정상 50건 중 high|medium 오탐 비율이 0.10 이하", () => {
    const falsePositives = NORMAL.filter((m) => {
      const r = detectSmishing(m);
      return r.risk === "high" || r.risk === "medium";
    }).length;
    const fpr = falsePositives / NORMAL.length;
    expect(fpr).toBeLessThanOrEqual(0.10);
  });
});

// ──────────────────────────────────────────────────────────────────
// 3. 분류 지연 ≤ 300ms
// ──────────────────────────────────────────────────────────────────
describe("분류 지연 ≤ 300ms", () => {
  test("100건 전체 분류가 300ms 이내", () => {
    const all = [...DANGEROUS, ...NORMAL];
    const start = Date.now();
    all.forEach((m) => detectSmishing(m));
    expect(Date.now() - start).toBeLessThan(300);
  });
});

// ──────────────────────────────────────────────────────────────────
// 4. matched 배열 검증
// ──────────────────────────────────────────────────────────────────
describe("detectSmishing() — matched 필드", () => {
  test("위험 문자 → matched 배열이 비어있지 않음", () => {
    const r = detectSmishing("[검찰청] 귀하는 범죄수사 대상입니다. 즉시 연락하세요.");
    expect(r.matched.length).toBeGreaterThan(0);
  });

  test("정상 문자 → matched 배열이 비어있음", () => {
    const r = detectSmishing("엄마 오늘 저녁 뭐 먹을까요?");
    expect(r.matched).toHaveLength(0);
  });

  test("복합 위험 → 여러 규칙이 matched에 포함", () => {
    const r = detectSmishing("검찰청에서 수사 중입니다. OTP를 알려주세요. 지금 즉시 대응하세요.");
    expect(r.matched.length).toBeGreaterThanOrEqual(2);
  });
});

// ──────────────────────────────────────────────────────────────────
// 5. 빈 문자열 / 짧은 문자열
// ──────────────────────────────────────────────────────────────────
describe("detectSmishing() — 엣지케이스", () => {
  test("빈 문자열 → low", () => {
    expect(detectSmishing("").risk).toBe("low");
  });

  test("숫자만 → low", () => {
    expect(detectSmishing("01012345678").risk).toBe("low");
  });

  test("영문만 → low", () => {
    expect(detectSmishing("Hello there").risk).toBe("low");
  });
});
